(function (root) {
  'use strict';
  root.STORY = {
    list: [],
    map: {},
    premise: 'Три недели назад Король-Лич Мортимер украл у Смерти её косу. С тех пор в долине Гнилодол никто не может умереть: ни старики, ни казнённые, ни курица, которую трижды пытались сварить к ужину. Смерть сидит в таверне «Последний вздох», пьёт и жалуется на жизнь. Её работу кое-как тянет стажёр с учебным серпом — он забирает только тех, кто *особенно* постарался.',
    add: function (h) { this.list.push(h); this.map[h.id] = h; },
    get: function (id) { return this.map[id]; }
  };
})(window);
